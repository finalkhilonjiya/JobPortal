-- property events: saved-search matches, approval, rejection, price drops
create or replace function public.on_property_change()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.status = 'active' and (tg_op = 'INSERT' or old.status is distinct from 'active') then
    insert into public.notifications (user_id, title, body, kind, data)
    select s.user_id,
           'New match: ' || s.name,
           new.title || ' - ' || new.city,
           'saved_search',
           jsonb_build_object('property_id', new.id)
    from public.saved_searches s
    where s.alerts
      and s.user_id <> new.owner_id
      and (s.filters->>'purpose'  is null or s.filters->>'purpose'  = new.purpose)
      and (s.filters->>'category' is null or s.filters->>'category' = new.category)
      and (s.filters->>'city'     is null or lower(s.filters->>'city') = lower(new.city))
      and (s.filters->>'max_price' is null or new.price <= (s.filters->>'max_price')::numeric);
    if tg_op = 'UPDATE' and old.status = 'pending' then
      perform public.notify(new.owner_id, 'Listing approved', new.title || ' is now live.',
                            'listing', jsonb_build_object('property_id', new.id));
    end if;
  end if;

  if tg_op = 'UPDATE' and new.status = 'rejected' and old.status is distinct from 'rejected' then
    perform public.notify(new.owner_id, 'Listing rejected',
                          coalesce(new.reject_reason, 'Please review the details and post again.'),
                          'listing', jsonb_build_object('property_id', new.id));
  end if;

  if tg_op = 'UPDATE' and new.price_reduced_at is not null
     and new.price_reduced_at is distinct from old.price_reduced_at then
    insert into public.notifications (user_id, title, body, kind, data)
    select f.user_id, 'Price drop',
           new.title || ' is now cheaper.', 'price_drop',
           jsonb_build_object('property_id', new.id)
    from public.favorites f
    where f.property_id = new.id and f.user_id <> new.owner_id;
  end if;
  return new;
end $$;

drop trigger if exists properties_notify on public.properties;
create trigger properties_notify
  after insert or update on public.properties
