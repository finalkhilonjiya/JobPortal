create or replace function public.protect_admin_columns()
returns trigger language plpgsql security definer set search_path = public as $$
declare auto boolean;
begin
  if tg_op = 'INSERT' then
    if auth.uid() is not null and not public.is_admin() then
      new.is_verified := false;
      new.is_featured := false;
      new.featured_until := null;
      new.reject_reason := null;
      select coalesce((value)::text::boolean, true) into auto
        from public.app_settings where key = 'auto_approve';
      new.status := case when coalesce(auto, true) then 'active' else 'pending' end;
    end if;
  else
    if auth.uid() is not null and not public.is_admin() then
      new.is_verified := old.is_verified;
      new.is_featured := old.is_featured;
      new.featured_until := old.featured_until;
      new.reject_reason := old.reject_reason;
      if old.status in ('pending','rejected') then new.status := old.status; end if;
      if new.status in ('pending','rejected') then new.status := old.status; end if;
    end if;
    if new.price is distinct from old.price then
      if new.price < old.price then
        new.previous_price := old.price;
        new.price_reduced_at := now();
      else
        new.previous_price := null;
        new.price_reduced_at := null;
      end if;
    end if;
  end if;
  new.updated_at := now();
  return new;
end $$;

