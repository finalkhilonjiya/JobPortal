create or replace function public.get_or_create_conversation(p_property uuid, p_owner uuid)
returns uuid language plpgsql security definer set search_path = public as $$
declare cid uuid;
begin
  if auth.uid() is null then raise exception 'not logged in'; end if;
  if auth.uid() = p_owner then raise exception 'cannot chat with yourself'; end if;
  if public.is_blocked(auth.uid(), p_owner) then raise exception 'blocked'; end if;
  select id into cid from public.conversations
    where property_id is not distinct from p_property
      and buyer_id = auth.uid() and owner_id = p_owner;
  if cid is null then
    insert into public.conversations (property_id, buyer_id, owner_id)
    values (p_property, auth.uid(), p_owner) returning id into cid;
  end if;
  return cid;
end $$;
revoke all on function public.get_or_create_conversation(uuid, uuid) from public, anon;
grant execute on function public.get_or_create_conversation(uuid, uuid) to authenticated;

create or replace function public.mark_conversation_read(p_id uuid)
returns void language plpgsql security definer set search_path = public as $$
begin
  update public.conversations set
