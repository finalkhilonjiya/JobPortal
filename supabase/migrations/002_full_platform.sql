create or replace function public.locality_stats(p_city text, p_locality text)
returns jsonb language sql stable security definer set search_path = public as $$
  with base as (
    select purpose, price,
           nullif(coalesce(area_sqft, super_builtup_area, builtup_area, carpet_area), 0) as area
    from public.properties
    where status in ('active','rented','sold')
      and lower(city) = lower(p_city)
      and (p_locality is null or p_locality = '' or lower(locality) = lower(p_locality))
  )
  select jsonb_build_object(
    'sale_count', (select count(*) from base where purpose = 'sale'),
    'rent_count', (select count(*) from base where purpose = 'rent'),
    'avg_sale',   (select round(avg(price)) from base where purpose = 'sale'),
    'avg_sale_psf', (select round(avg(price / area)) from base where purpose = 'sale' and area is not null),
    'avg_rent',   (select round(avg(price)) from base where purpose = 'rent'),
    'avg_rent_psf', (select round(avg(price / area), 1) from base where purpose = 'rent' and area is not null)
  );
$$;
grant execute on function public.locality_stats(text, text) to anon, authenticated;

create or replace function public.locality_trend(p_city text, p_locality text, p_purpose text)
returns table (month date, avg_price numeric, listings int)
language sql stable security definer set search_path = public as $$
