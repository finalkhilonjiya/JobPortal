create or replace function public.admin_review_promotion(p_id uuid, p_approve boolean)
returns void language plpgsql security definer set search_path = public as $$
declare r record; days int;
begin
  if not public.is_admin() then raise exception 'admin only'; end if;
  select * into r from public.promotion_requests where id = p_id;
  if r.id is null then raise exception 'not found'; end if;
  if p_approve then
    days := case r.plan when 'featured_7' then 7 else 30 end;
    update public.properties set is_featured = true, featured_until = now() + (days || ' days')::interval
      where id = r.property_id;
    update public.promotion_requests set status = 'approved' where id = p_id;
    perform public.notify(r.user_id, 'Promotion approved', 'Your listing is now featured for ' || days || ' days.',
                          'promotion', jsonb_build_object('property_id', r.property_id));
  else
    update public.promotion_requests set status = 'rejected' where id = p_id;
    perform public.notify(r.user_id, 'Promotion not approved', 'Please contact support for details.',
                          'promotion', jsonb_build_object('property_id', r.property_id));
  end if;
end $$;
revoke all on function public.admin_review_promotion(uuid, boolean) from public, anon;
grant execute on function public.admin_review_promotion(uuid, boolean) to authenticated;

