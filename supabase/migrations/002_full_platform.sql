    and purpose = p_purpose
    and lower(city) = lower(p_city)
    and (p_locality is null or p_locality = '' or lower(locality) = lower(p_locality))
    and created_at > now() - interval '12 months'
  group by 1 order by 1;
$$;
grant execute on function public.locality_trend(text, text, text) to anon, authenticated;

create or replace function public.estimate_price(p_city text, p_locality text, p_purpose text, p_area numeric)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare psf numeric; n int; scope text := 'locality';
begin
  select avg(price / a), count(*) into psf, n from (
    select price, nullif(coalesce(area_sqft, super_builtup_area, builtup_area, carpet_area), 0) as a
    from public.properties
    where status in ('active','rented','sold') and purpose = p_purpose
      and lower(city) = lower(p_city) and lower(locality) = lower(p_locality)) t
  where a is not null;
  if coalesce(n, 0) < 3 then
    scope := 'city';
    select avg(price / a), count(*) into psf, n from (
      select price, nullif(coalesce(area_sqft, super_builtup_area, builtup_area, carpet_area), 0) as a
      from public.properties
      where status in ('active','rented','sold') and purpose = p_purpose
        and lower(city) = lower(p_city)) t
    where a is not null;
  end if;
  if coalesce(n, 0) = 0 or psf is null then
    return jsonb_build_object('scope', 'none', 'samples', 0);
  end if;
  return jsonb_build_object('scope', scope, 'samples', n, 'psf', round(psf, 2),
                            'estimate', round(psf * p_area));
end $$;
grant execute on function public.estimate_price(text, text, text, numeric) to anon, authenticated;

